def get_subject(target_age, ethnicity):
    subject = f"a {ethnicity} {target_age} year"
    if target_age <= 8:
        subject += " very young child"
    elif target_age <= 11:
        subject += " young child"
    elif target_age <= 13:
        subject += " preteen"
    elif target_age <= 19:
        subject += " old teenager"
    elif target_age <= 24:
        subject += " young adult, youthful face, smooth skin"
    elif target_age <= 29:
        subject += " adult approaching thirty, mature young adult, smooth skin"
    elif target_age <= 34:
        subject += " adult in their early thirties, subtly mature facial features, slight signs of aging"
    elif target_age <= 39:
        subject += " adult in their late thirties, mature facial features, visible facial lines"
    elif target_age <= 44:
        subject += " adult in their early forties, mature facial structure, visible facial lines"
    elif target_age <= 49:
        subject += " middle aged adult, noticeable facial lines, mature appearance"
    elif target_age <= 54:
        subject += " older middle aged adult, noticeable wrinkles, aging facial features, mature appearance"
    elif target_age <= 59:
        subject += " older aged adult, visible wrinkles, clearly aged face"
    elif target_age <= 69:
        subject += " senior adult, prominent wrinkles, noticeably aged face"
    else:
        subject += " elderly senior adult, deep wrinkles, strongly aged facial features"
    return subject

def select_hair_color(age, traits, rng):
    if age >= 65:
        return rng.choice([
            "gray hair",
            "white hair",
            "light gray hair",
            "dark gray hair",
            "salt-and-pepper hair",
        ])
    hair_color = rng.choice(traits["hair_colors"])
    if age >= 50:
        hair_color = f"graying {hair_color}"
    elif age >= 40:
        hair_color = f"slightly graying {hair_color}"
    elif age >= 35:
        hair_color = f"a few gray strands in {hair_color}"
    return hair_color